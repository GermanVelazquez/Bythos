package com.bythos.movil

import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Encrypts and decrypts opaque bytes; injectable so the store logic runs on the JVM. */
interface TokenCipher {
    fun encrypt(claro: ByteArray): ByteArray
    fun decrypt(cifrado: ByteArray): ByteArray
}

/** Minimal key/value seam over SharedPreferences. */
interface ClaveValor {
    fun leer(clave: String): String?
    fun escribir(clave: String, valor: String)
    fun borrar(clave: String)
}

class SharedPreferencesClaveValor(private val prefs: SharedPreferences) : ClaveValor {
    override fun leer(clave: String): String? = prefs.getString(clave, null)
    override fun escribir(clave: String, valor: String) = prefs.edit().putString(clave, valor).apply()
    override fun borrar(clave: String) = prefs.edit().remove(clave).apply()
}

/**
 * AES-GCM over any SecretKey. The IV is generated by the Cipher (Android Keystore
 * keys require randomized encryption) and stored as: iv length byte | iv | ciphertext+tag.
 */
class AesGcmCipher(private val clave: () -> SecretKey) : TokenCipher {

    override fun encrypt(claro: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMACION)
        cipher.init(Cipher.ENCRYPT_MODE, clave())
        val iv = cipher.iv
        return byteArrayOf(iv.size.toByte()) + iv + cipher.doFinal(claro)
    }

    override fun decrypt(cifrado: ByteArray): ByteArray {
        require(cifrado.isNotEmpty()) { "blob vacío" }
        val n = cifrado[0].toInt()
        require(n > 0 && cifrado.size > 1 + n) { "blob truncado" }
        val cipher = Cipher.getInstance(TRANSFORMACION)
        cipher.init(Cipher.DECRYPT_MODE, clave(), GCMParameterSpec(TAG_BITS, cifrado, 1, n))
        return cipher.doFinal(cifrado, 1 + n, cifrado.size - 1 - n)
    }

    companion object {
        private const val TRANSFORMACION = "AES/GCM/NoPadding"
        private const val TAG_BITS = 128

        /** Non-exportable AES-256 key in the Android Keystore, created on first use. */
        fun androidKeystore(alias: String = "bythos_token"): AesGcmCipher = AesGcmCipher {
            val ks = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
            (ks.getKey(alias, null) as? SecretKey) ?: KeyGenerator
                .getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
                .apply {
                    init(
                        KeyGenParameterSpec.Builder(
                            alias,
                            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                        )
                            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                            .setKeySize(256)
                            .build(),
                    )
                }
                .generateKey()
        }
    }
}

/** The pairing token never touches disk in clear: only its Keystore-encrypted form is stored. */
class KeystoreTokenStore(
    private val almacen: ClaveValor,
    private val cipher: TokenCipher,
) {
    fun guardar(token: String) {
        val blob = cipher.encrypt(token.toByteArray(Charsets.UTF_8))
        almacen.escribir(CLAVE, Base64.getEncoder().encodeToString(blob))
    }

    /** Null when absent or unreadable (corrupt blob, invalidated key); an unreadable one is dropped so the app re-pairs. */
    fun leer(): String? {
        val guardado = almacen.leer(CLAVE) ?: return null
        return try {
            String(cipher.decrypt(Base64.getDecoder().decode(guardado)), Charsets.UTF_8)
        } catch (e: Exception) {
            almacen.borrar(CLAVE)
            null
        }
    }

    fun borrar() = almacen.borrar(CLAVE)

    companion object {
        private const val CLAVE = "token_cifrado"

        fun deContexto(prefs: SharedPreferences) =
            KeystoreTokenStore(SharedPreferencesClaveValor(prefs), AesGcmCipher.androidKeystore())
    }
}
